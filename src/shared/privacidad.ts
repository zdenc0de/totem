export type BloqueAviso =
  | { tipo: 'titulo'; texto: string }
  | { tipo: 'parrafo'; texto: string }
  | { tipo: 'lista'; items: string[] }

export function bloquesAviso(texto: string): BloqueAviso[] {
  return texto
    .split(/\n\s*\n/)
    .map((bloque) => bloque.trim())
    .filter(Boolean)
    .map((bloque): BloqueAviso => {
      if (bloque.startsWith('## ')) return { tipo: 'titulo', texto: bloque.slice(3).trim() }
      const lineas = bloque.split('\n').map((l) => l.trim())
      if (lineas.every((l) => l.startsWith('- '))) {
        return { tipo: 'lista', items: lineas.map((l) => l.slice(2).trim()) }
      }
      return { tipo: 'parrafo', texto: lineas.join('\n') }
    })
}
